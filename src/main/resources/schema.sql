-- Ticket Chess schema (PostgreSQL + H2 MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE)
-- Column names match EclipseLink defaults (lowercase, camelCase fields without underscores).

CREATE TABLE IF NOT EXISTS organisation (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_url VARCHAR(500) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    settings_json TEXT,
    CONSTRAINT uk_organisation_base_url UNIQUE (base_url)
);

CREATE TABLE IF NOT EXISTS club_season (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    org_id INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_current BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS license (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    org_id INTEGER NOT NULL,
    name VARCHAR(50) NOT NULL,
    access_rule VARCHAR(32) NOT NULL,
    CONSTRAINT uk_license_org_name UNIQUE (org_id, name)
);

CREATE TABLE IF NOT EXISTS license_price (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    category VARCHAR(10) NOT NULL,
    price_cents INTEGER NOT NULL,
    license_id INTEGER NOT NULL,
    CONSTRAINT uk_license_price_category UNIQUE (category, license_id),
    CONSTRAINT fk_license_price_license FOREIGN KEY (license_id) REFERENCES license (id)
);

CREATE TABLE IF NOT EXISTS event_group (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    shortname VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS big_event (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS event (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id INTEGER NOT NULL,
    name VARCHAR(255) NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    pricecents BIGINT,
    youngpricecents BIGINT,
    status_id SMALLINT NOT NULL,
    event_type SMALLINT NOT NULL,
    event_group_id INTEGER,
    big_event_id INTEGER,
    description TEXT,
    CONSTRAINT fk_event_group FOREIGN KEY (event_group_id) REFERENCES event_group (id),
    CONSTRAINT fk_event_big_event FOREIGN KEY (big_event_id) REFERENCES big_event (id)
);

CREATE INDEX IF NOT EXISTS idx_event_status_id ON event (status_id);
CREATE INDEX IF NOT EXISTS idx_event_start_date ON event (start_date);

CREATE TABLE IF NOT EXISTS eventoption (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type VARCHAR(64) NOT NULL,
    option_value VARCHAR(255) NOT NULL,
    event_id INTEGER,
    CONSTRAINT fk_eventoption_event FOREIGN KEY (event_id) REFERENCES event (id)
);

CREATE TABLE IF NOT EXISTS eventcollectionoption (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_type VARCHAR(64) NOT NULL,
    option_value VARCHAR(255) NOT NULL,
    big_event_id INTEGER,
    CONSTRAINT fk_eventcollectionoption_big_event FOREIGN KEY (big_event_id) REFERENCES big_event (id)
);

CREATE TABLE IF NOT EXISTS payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    stripesessionid VARCHAR(255),
    stripeintent VARCHAR(255),
    useremail VARCHAR(255) NOT NULL,
    payername VARCHAR(255),
    payeraddress VARCHAR(1000),
    donation BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(32),
    type VARCHAR(32),
    amountcents BIGINT,
    CONSTRAINT uk_payment_stripesessionid UNIQUE (stripesessionid)
);

CREATE TABLE IF NOT EXISTS player_subscription (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    nr_ffe VARCHAR(255),
    creation_user VARCHAR(255),
    event_id INTEGER NOT NULL,
    status SMALLINT NOT NULL,
    payment_id BIGINT,
    amountcents BIGINT,
    attendance_at TIMESTAMP,
    CONSTRAINT fk_player_subscription_event FOREIGN KEY (event_id) REFERENCES event (id),
    CONSTRAINT fk_player_subscription_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
);

CREATE INDEX IF NOT EXISTS idx_player_subscription_event_id ON player_subscription (event_id);
CREATE INDEX IF NOT EXISTS idx_player_subscription_creation_user ON player_subscription (creation_user);

CREATE TABLE IF NOT EXISTS player_subscription_option (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    player_subscription_id INTEGER NOT NULL,
    amountcents BIGINT,
    description VARCHAR(512),
    payment_id BIGINT,
    status SMALLINT NOT NULL,
    CONSTRAINT fk_pso_subscription FOREIGN KEY (player_subscription_id) REFERENCES player_subscription (id),
    CONSTRAINT fk_pso_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
);

CREATE TABLE IF NOT EXISTS player_pending_subscription (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    nr_ffe VARCHAR(255),
    creation_user VARCHAR(255),
    event_id INTEGER NOT NULL,
    CONSTRAINT fk_pending_subscription_event FOREIGN KEY (event_id) REFERENCES event (id)
);

CREATE TABLE IF NOT EXISTS membership (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    creation_user VARCHAR(255) NOT NULL,
    nr_ffe VARCHAR(255) NOT NULL,
    lastname VARCHAR(255),
    firstname VARCHAR(255),
    birthdate VARCHAR(255),
    club_ref INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    amountcents INTEGER NOT NULL,
    license_type VARCHAR(10),
    season_id INTEGER,
    payment_id BIGINT,
    CONSTRAINT fk_membership_season FOREIGN KEY (season_id) REFERENCES club_season (id),
    CONSTRAINT fk_membership_payment FOREIGN KEY (payment_id) REFERENCES payment (id)
);

CREATE TABLE IF NOT EXISTS membership_option (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    option_type VARCHAR(64) NOT NULL,
    option_value VARCHAR(255) NOT NULL,
    amount_cents INTEGER,
    access_rule VARCHAR(32),
    license_id INTEGER,
    season_id INTEGER,
    CONSTRAINT fk_membership_option_license FOREIGN KEY (license_id) REFERENCES license (id),
    CONSTRAINT fk_membership_option_season FOREIGN KEY (season_id) REFERENCES club_season (id)
);

CREATE TABLE IF NOT EXISTS membership_option_subscription (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    nr_ffe VARCHAR(255),
    membership_id INTEGER NOT NULL,
    membership_option_id INTEGER NOT NULL,
    CONSTRAINT fk_mos_membership FOREIGN KEY (membership_id) REFERENCES membership (id),
    CONSTRAINT fk_mos_option FOREIGN KEY (membership_option_id) REFERENCES membership_option (id)
);

CREATE TABLE IF NOT EXISTS membership_option_file (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    membership_option_id INTEGER NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    stored_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(120),
    size_bytes BIGINT,
    uploaded_by VARCHAR(255),
    CONSTRAINT fk_membership_option_file_option FOREIGN KEY (membership_option_id) REFERENCES membership_option (id)
);

CREATE TABLE IF NOT EXISTS custom_player (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    licence VARCHAR(255),
    birthdate VARCHAR(255),
    creation_user VARCHAR(255),
    gender BOOLEAN,
    elo VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS user_authorization (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    role VARCHAR(64) NOT NULL,
    scope_type VARCHAR(32) NOT NULL,
    scope_id INTEGER,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    valid_until TIMESTAMP,
    granted_by VARCHAR(320),
    CONSTRAINT uk_user_auth_grant UNIQUE (email, role, scope_type, scope_id)
);

CREATE INDEX IF NOT EXISTS idx_user_auth_email ON user_authorization (email);
CREATE INDEX IF NOT EXISTS idx_user_auth_lookup ON user_authorization (email, role, scope_type, scope_id, active);
